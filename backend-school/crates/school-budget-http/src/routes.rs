use crate::{handlers, state::BudgetHttpState};
use axum::Router;

#[inline(never)]
pub fn protected_routes() -> Router<BudgetHttpState> {
    Router::new()
        .route(
            "/budget/catalogs",
            axum::routing::get(handlers::get_catalogs),
        )
        .route(
            "/budget/settings",
            axum::routing::get(handlers::get_settings),
        )
        .route(
            "/budget/fiscal-years",
            axum::routing::post(handlers::create_fiscal_year),
        )
        .route(
            "/budget/fiscal-years/{id}",
            axum::routing::get(handlers::get_year_settings)
                .put(handlers::save_year_settings)
                .delete(handlers::delete_fiscal_year),
        )
        .route(
            "/budget/fiscal-years/{id}/funding",
            axum::routing::put(handlers::save_received_funding),
        )
        .route(
            "/budget/fiscal-years/{id}/close",
            axum::routing::post(handlers::close_fiscal_year),
        )
        .route(
            "/budget/projects",
            axum::routing::get(handlers::list_projects).post(handlers::create_project),
        )
        .route(
            "/budget/projects/{id}",
            axum::routing::get(handlers::get_project)
                .put(handlers::save_project)
                .delete(handlers::delete_project),
        )
        .route(
            "/budget/projects/{id}/submit",
            axum::routing::post(handlers::submit_project),
        )
        .route(
            "/budget/projects/{id}/actions",
            axum::routing::post(handlers::act_project),
        )
        .route(
            "/budget/projects/{id}/amendments",
            axum::routing::post(handlers::amend_project),
        )
        .route(
            "/budget/requests",
            axum::routing::get(handlers::list_requests),
        )
        .route(
            "/budget/projects/{id}/requests",
            axum::routing::post(handlers::create_request),
        )
        .route(
            "/budget/requests/{id}",
            axum::routing::get(handlers::get_request).put(handlers::save_request),
        )
        .route(
            "/budget/requests/{id}/submit",
            axum::routing::post(handlers::submit_request),
        )
        .route(
            "/budget/requests/{id}/actions",
            axum::routing::post(handlers::act_request),
        )
        .route(
            "/budget/requests/{id}/close",
            axum::routing::post(handlers::close_request),
        )
        .route(
            "/budget/requests/{id}/payments",
            axum::routing::get(handlers::list_payments).post(handlers::create_payment),
        )
        .route(
            "/budget/adjustments",
            axum::routing::get(handlers::list_adjustments).post(handlers::create_adjustment),
        )
        .route(
            "/budget/adjustments/{id}",
            axum::routing::get(handlers::get_adjustment).put(handlers::save_adjustment),
        )
        .route(
            "/budget/adjustments/{id}/submit",
            axum::routing::post(handlers::submit_adjustment),
        )
        .route(
            "/budget/adjustments/{id}/actions",
            axum::routing::post(handlers::act_adjustment),
        )
        .route(
            "/budget/dashboard",
            axum::routing::get(handlers::get_dashboard),
        )
        .route(
            "/budget/projects/{id}/process",
            axum::routing::get(handlers::project_process),
        )
        .route(
            "/budget/projects/{id}/history",
            axum::routing::get(handlers::project_history),
        )
        .route(
            "/budget/requests/{id}/process",
            axum::routing::get(handlers::request_process),
        )
        .route(
            "/budget/requests/{id}/history",
            axum::routing::get(handlers::request_history),
        )
        .route(
            "/budget/adjustments/{id}/process",
            axum::routing::get(handlers::adjustment_process),
        )
        .route(
            "/budget/adjustments/{id}/history",
            axum::routing::get(handlers::adjustment_history),
        )
        .route(
            "/budget/requests/{id}/payments/{paymentId}/refunds",
            axum::routing::post(handlers::refund_payment),
        )
        .route(
            "/budget/reports/export",
            axum::routing::get(handlers::export_report),
        )
}
