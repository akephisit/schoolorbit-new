use super::{handlers, state::SupervisionHttpState};
use axum::{
    routing::{get, patch, post, put},
    Router,
};

pub fn protected_routes() -> Router<SupervisionHttpState> {
    Router::new()
        .route("/calendar", get(handlers::list_calendar))
        .route(
            "/cycles",
            get(handlers::list_cycles).post(handlers::create_cycle),
        )
        .route(
            "/cycles/{id}",
            get(handlers::get_cycle)
                .patch(handlers::update_cycle)
                .delete(handlers::delete_cycle),
        )
        .route(
            "/cycles/{id}/deletion-impact",
            get(handlers::cycle_deletion_impact),
        )
        .route("/booking-options", get(handlers::booking_options))
        .route(
            "/templates",
            get(handlers::list_templates).post(handlers::create_template),
        )
        .route(
            "/templates/summaries",
            get(handlers::list_template_summaries),
        )
        .route(
            "/templates/{id}/summary",
            get(handlers::get_template_summary),
        )
        .route(
            "/templates/{id}",
            get(handlers::get_template).patch(handlers::update_template),
        )
        .route("/observations", get(handlers::list_observations))
        .route(
            "/observations/requests",
            post(handlers::request_observation),
        )
        .route(
            "/observations/{id}",
            get(handlers::get_observation).patch(handlers::update_observation),
        )
        .route(
            "/observations/{id}/review",
            get(handlers::get_observation_review),
        )
        .route(
            "/observations/{id}/evaluator-availability",
            get(handlers::evaluator_availability),
        )
        .route(
            "/observations/{id}/timetable-options",
            get(handlers::observation_timetable_options),
        )
        .route(
            "/observations/{id}/evaluators",
            put(handlers::replace_observation_evaluators),
        )
        .route(
            "/observations/{id}/cancel",
            post(handlers::cancel_observation),
        )
        .route(
            "/observations/{id}/resubmit-request",
            post(handlers::resubmit_observation_request),
        )
        .route(
            "/observations/{id}/request",
            patch(handlers::update_requested_observation)
                .delete(handlers::cancel_requested_observation),
        )
        .route(
            "/observations/{id}/approve-request",
            post(handlers::approve_observation_request),
        )
        .route(
            "/observations/{id}/return-request",
            post(handlers::return_observation_request),
        )
        .route(
            "/observations/{id}/evaluations/me/submit",
            post(handlers::submit_my_evaluation),
        )
        .route(
            "/observations/{id}/acknowledge",
            post(handlers::acknowledge_observation),
        )
        .route(
            "/reports/cycles/{id}/progress",
            get(handlers::cycle_progress),
        )
        .route(
            "/reports/cycles/{id}/teacher-status",
            get(handlers::teacher_status_overview),
        )
}
