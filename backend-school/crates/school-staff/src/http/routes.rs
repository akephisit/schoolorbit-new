use super::handlers;
use crate::http::state::StaffHttpState;
use axum::{
    routing::{delete, get, put},
    Router,
};

pub fn protected_routes() -> Router<StaffHttpState> {
    Router::new()
        .route(
            "/staff",
            get(handlers::staff::list_staff).post(handlers::staff::create_staff),
        )
        .route(
            "/staff/dashboard",
            get(handlers::staff::get_staff_dashboard),
        )
        .route(
            "/staff/personnel-rank-milestones",
            get(handlers::personnel::get_rank_milestone_overview),
        )
        .route(
            "/staff/personnel-overview",
            get(handlers::personnel::get_personnel_overview),
        )
        .route(
            "/staff/job-positions",
            get(handlers::personnel::list_job_positions),
        )
        .route(
            "/staff/{id}",
            get(handlers::staff::get_staff_profile)
                .put(handlers::staff::update_staff)
                .delete(handlers::staff::delete_staff),
        )
        .route(
            "/staff/{id}/career-history",
            get(handlers::career::list_career_history)
                .post(handlers::career::append_career_history),
        )
        .route(
            "/staff/{id}/career-history/{entryId}",
            axum::routing::patch(handlers::career::correct_career_history),
        )
        .route(
            "/staff/{id}/public-profile",
            get(handlers::staff::get_public_staff_profile),
        )
        .route(
            "/roles",
            get(handlers::roles::list_roles).post(handlers::roles::create_role),
        )
        .route(
            "/roles/{id}",
            get(handlers::roles::get_role)
                .put(handlers::roles::update_role)
                .delete(handlers::roles::deactivate_role),
        )
        .route(
            "/organization/units",
            get(handlers::roles::list_organization_units)
                .post(handlers::roles::create_organization_unit),
        )
        .route(
            "/organization/units/{id}",
            get(handlers::roles::get_organization_unit)
                .put(handlers::roles::update_organization_unit)
                .delete(handlers::roles::deactivate_organization_unit),
        )
        .route(
            "/organization/units/{id}/permissions",
            get(handlers::organization_permissions::get_organization_permissions)
                .put(handlers::organization_permissions::update_organization_permissions),
        )
        .route(
            "/organization/units/{id}/delegatable-permissions",
            get(handlers::organization_delegations::list_delegatable_permissions),
        )
        .route(
            "/organization/units/{id}/delegations",
            get(handlers::organization_delegations::list_delegations)
                .post(handlers::organization_delegations::create_delegation),
        )
        .route(
            "/organization/delegations/{id}",
            delete(handlers::organization_delegations::revoke_delegation),
        )
        .route(
            "/organization/units/{id}/members",
            get(handlers::organization_members::list_members)
                .post(handlers::organization_members::add_member),
        )
        .route(
            "/organization/units/{id}/members/{user_id}",
            put(handlers::organization_members::update_member)
                .delete(handlers::organization_members::remove_member),
        )
        .route(
            "/users/{id}/roles",
            get(handlers::user_roles::get_user_roles).post(handlers::user_roles::assign_user_role),
        )
        .route(
            "/users/{id}/roles/{role_id}",
            delete(handlers::user_roles::remove_user_role),
        )
        .route(
            "/users/{id}/permissions",
            get(handlers::user_roles::get_user_permissions),
        )
        .route("/permissions", get(handlers::permissions::list_permissions))
        .route(
            "/permissions/modules",
            get(handlers::permissions::list_permissions_by_module),
        )
}
